public class q1
{
    public static void main(String[] args)
    {
        //for
        for(int i=2;i<=20;i=i+2)
        {
            System.out.println(i);
        }
        
        //while
        
        int j=2;
        while(j<=20)
        {
            System.out.println(j);
            j=j+2;
        }
        
        //do while
        
        int k=2;
        do
        {
            System.out.println(k);
            k=k+2;
            
        }
        while(k<=20);
    }
}